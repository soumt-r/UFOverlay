"""Generate src/vr/fntable.rs: function-slot indices for OpenVR C FnTables.

UFOverlay talks to OpenVR through the flat "FnTable:" interfaces, which are
plain arrays of function pointers. Instead of a full bindgen layer we only need
the *slot index* of each function; the signatures are declared by hand at the
call sites. Indices come straight from the header so they can never drift.

usage: python tools/gen_fntable.py vendor/openvr_capi.h > src/vr/fntable.rs
"""
import re
import sys

WANT = ["IVRSystem", "IVROverlay", "IVRApplications", "IVRInput"]

src = open(sys.argv[1], encoding="utf-8").read()
out = ["// @generated by tools/gen_fntable.py — do not edit", ""]

for iface in WANT:
    ver = re.search(r'static const char \* %s_Version = "(\w+)";' % iface, src).group(1)
    body = re.search(r"struct VR_%s_FnTable\s*\{(.*?)\};" % iface, src, re.S).group(1)
    names = re.findall(r"\(OPENVR_FNTABLE_CALLTYPE \*(\w+)\)", body)
    out.append("#[allow(non_upper_case_globals, dead_code)]")
    out.append("pub mod %s {" % iface.lower())
    out.append('    pub const VERSION: &str = "FnTable:%s\\0";' % ver)
    for i, n in enumerate(names):
        out.append("    pub const %s: usize = %d;" % (n, i))
    out.append("}")
    out.append("")

sys.stdout.write("\n".join(out))
